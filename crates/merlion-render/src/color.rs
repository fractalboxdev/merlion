/// The sRGB value of a CSS named colour (lower-case).
pub fn named_rgb(name: &str) -> Option<Rgba8> {
    NAMED_RGB
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .and_then(|i| NAMED_RGB.get(i))
        .map(|(_, [r, g, b])| Rgba8::new(*r, *g, *b, 255))
}

/// `hsl(h s% l% / a)` as 8-bit sRGB (CSS Color 4 `hslToRgb`): `h` in degrees, `s` and
/// `l` in percent, `a` in 0..=1. Non-finite components give `None`.
pub fn hsl_to_rgba8(h: f64, s: f64, l: f64, a: f64) -> Option<Rgba8> {
    if !(h.is_finite() && s.is_finite() && l.is_finite() && a.is_finite()) {
        return None;
    }
    let h = h - 360.0 * math::floor(h / 360.0);
    let s = math::clamp(s, 0.0, 100.0) / 100.0;
    let l = math::clamp(l, 0.0, 100.0) / 100.0;
    let amp = s * math::min(l, 1.0 - l);
    let f = |n: f64| {
        let k0 = n + h / 30.0;
        let k = k0 - 12.0 * math::floor(k0 / 12.0);
        let t = math::min(math::min(k - 3.0, 9.0 - k), 1.0);
        let v = l - amp * math::max(-1.0, t);
        math::round(math::clamp(v, 0.0, 1.0) * 255.0) as u8
    };
    Some(Rgba8::new(f(0.0), f(8.0), f(4.0), alpha8(a)))
}

impl Rgba8 {
    /// A typed source colour as 8-bit sRGB; `None` for `none` and unusable values.
    pub fn from_color(c: &Color) -> Option<Rgba8> {
        match *c {
            Color::Rgba { r, g, b, a } => Some(Rgba8::new(r, g, b, a)),
            Color::Hsla { h, s, l, a } => hsl_to_rgba8(h, s, l, a),
            Color::Named(n) => named_rgb(n),
            Color::Transparent => Some(Rgba8::new(0, 0, 0, 0)),
            Color::None => None,
        }
    }
}
