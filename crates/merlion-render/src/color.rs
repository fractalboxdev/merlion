//! Colour arithmetic in software (specs/architecture.md#determinism,
//! specs/svg-output.md#palette).
//!
//! `oklab_mix` reproduces CSS `color-mix(in oklab, A p%, B)`: 8-bit sRGB → linear light
//! through a 256-entry constant table, linear → OKLab with `cbrt` by Newton iteration,
//! interpolation with premultiplied alpha, then back, cubing instead of `powf`, and
//! linear → 8-bit sRGB by binary search over the channel midpoints. Only `+ − × ÷` and
//! comparisons run, so every target gives the same bits; `no_std` has no `powf`/`cbrt`.
//! The result matches an `f64` reference of CSS Color 4 to ±1 per channel.

use alloc::string::String;
use core::fmt::Write;

use crate::math;
use crate::model::Color;

/// An 8-bit sRGB colour with 8-bit alpha.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Rgba8 {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: u8,
}

impl Rgba8 {
    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {
        Rgba8 { r, g, b, a }
    }

    /// `#rgb`, `#rgba`, `#rrggbb` or `#rrggbbaa`.
    pub fn from_hex(s: &str) -> Option<Self> {
        let h = s.strip_prefix('#')?.as_bytes();
        let d = |i: usize| -> Option<u8> {
            let c = *h.get(i)?;
            match c {
                b'0'..=b'9' => Some(c - b'0'),
                b'a'..=b'f' => Some(c - b'a' + 10),
                b'A'..=b'F' => Some(c - b'A' + 10),
                _ => None,
            }
        };
        let two = |i: usize| -> Option<u8> { Some(d(i)? * 16 + d(i + 1)?) };
        match h.len() {
            3 => Some(Rgba8::new(d(0)? * 17, d(1)? * 17, d(2)? * 17, 255)),
            4 => Some(Rgba8::new(d(0)? * 17, d(1)? * 17, d(2)? * 17, d(3)? * 17)),
            6 => Some(Rgba8::new(two(0)?, two(2)?, two(4)?, 255)),
            8 => Some(Rgba8::new(two(0)?, two(2)?, two(4)?, two(6)?)),
            _ => None,
        }
    }

    /// `#rrggbb`, or `#rrggbbaa` when not opaque.
    pub fn to_hex(self) -> String {
        let mut s = String::with_capacity(9);
        let _ = write!(s, "#{:02x}{:02x}{:02x}", self.r, self.g, self.b);
        if self.a != 255 {
            let _ = write!(s, "{:02x}", self.a);
        }
        s
    }
}

