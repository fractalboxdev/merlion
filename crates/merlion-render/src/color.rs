/// Linear-light value of the 8-bit channel `c`.
pub fn to_linear(c: u8) -> f64 {
    SRGB_TO_LINEAR[c as usize]
}

/// The 8-bit channel whose sRGB level is nearest to linear-light `v` (rounding half up
/// in the gamma-encoded space, as CSS does), clamped to 0..=255.
pub fn from_linear(v: f64) -> u8 {
    if v.is_nan() {
        return 0;
    }
    // The number of midpoints at or below `v`.
    let (mut lo, mut hi) = (0usize, LINEAR_MIDPOINT.len());
    while lo < hi {
        let mid = (lo + hi) / 2;
        if LINEAR_MIDPOINT[mid] <= v {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    lo as u8
}

/// Cube root by Newton iteration from a fixed seed after scaling into [1/8, 1].
/// NaN and infinities give 0.
pub fn cbrt(x: f64) -> f64 {
    if !x.is_finite() {
        return 0.0;
    }
    if x == 0.0 {
        return x;
    }
    let neg = x < 0.0;
    let mut a = if neg { -x } else { x };
    let mut scale = 1.0;
    // At most ~360 steps each way over the f64 exponent range.
    for _ in 0..400 {
        if a <= 1.0 {
            break;
        }
        a /= 8.0;
        scale *= 2.0;
    }
    for _ in 0..400 {
        if a >= 0.125 {
            break;
        }
        a *= 8.0;
        scale /= 2.0;
    }
    let mut y = 0.75;
    for _ in 0..8 {
        y = (2.0 * y + a / (y * y)) / 3.0;
    }
    // One correction step in the unscaled domain removes the last-bit error.
    let mut r = y * scale;
    let t = if neg { -x } else { x };
    r -= (r * r * r - t) / (3.0 * r * r);
    if neg {
        -r
    } else {
        r
    }
}

type Lab = [f64; 3];

fn linear_to_oklab(r: f64, g: f64, b: f64) -> Lab {
    let l = cbrt(0.412_221_470_8 * r + 0.536_332_536_3 * g + 0.051_445_992_9 * b);
    let m = cbrt(0.211_903_498_2 * r + 0.680_699_545_1 * g + 0.107_396_956_6 * b);
    let s = cbrt(0.088_302_461_9 * r + 0.281_718_837_6 * g + 0.629_978_700_5 * b);
    [
        0.210_454_255_3 * l + 0.793_617_785_0 * m - 0.004_072_046_8 * s,
        1.977_998_495_1 * l - 2.428_592_205_0 * m + 0.450_593_709_9 * s,
        0.025_904_037_1 * l + 0.782_771_766_2 * m - 0.808_675_766_0 * s,
    ]
}

fn oklab_to_linear([ll, a, b]: Lab) -> [f64; 3] {
    let l = ll + 0.396_337_777_4 * a + 0.215_803_757_3 * b;
    let m = ll - 0.105_561_345_8 * a - 0.063_854_172_8 * b;
    let s = ll - 0.089_484_177_5 * a - 1.291_485_548_0 * b;
    let (l, m, s) = (l * l * l, m * m * m, s * s * s);
    [
        4.076_741_662_1 * l - 3.307_711_591_3 * m + 0.230_969_929_2 * s,
        -1.268_438_004_6 * l + 2.609_757_401_1 * m - 0.341_319_396_5 * s,
        -0.004_196_086_3 * l - 0.703_418_614_7 * m + 1.707_614_701_0 * s,
    ]
}

fn to_oklab(c: Rgba8) -> Lab {
    linear_to_oklab(to_linear(c.r), to_linear(c.g), to_linear(c.b))
}

fn alpha8(a: f64) -> u8 {
    math::round(math::clamp(a, 0.0, 1.0) * 255.0) as u8
}

/// CSS `color-mix(in oklab, a pct_a%, b)`: `pct_a` of `a`, the rest `b`, interpolated
/// in OKLab with premultiplied alpha. `pct_a` is clamped to 0..=100; NaN counts as 0.
pub fn oklab_mix(a: Rgba8, b: Rgba8, pct_a: f64) -> Rgba8 {
    let p = if pct_a.is_nan() {
        0.0
    } else {
        math::clamp(pct_a, 0.0, 100.0) / 100.0
    };
    if p == 1.0 {
        return a;
    }
    if p == 0.0 {
        return b;
    }
    let (aa, ab) = (a.a as f64 / 255.0, b.a as f64 / 255.0);
    let alpha = aa * p + ab * (1.0 - p);
    if alpha <= 0.0 {
        return Rgba8::new(0, 0, 0, 0);
    }
    let (la, lb) = (to_oklab(a), to_oklab(b));
    let mut m = [0.0; 3];
    for (i, v) in m.iter_mut().enumerate() {
        *v = (la[i] * aa * p + lb[i] * ab * (1.0 - p)) / alpha;
    }
    let [r, g, bl] = oklab_to_linear(m);
    Rgba8::new(
        from_linear(r),
        from_linear(g),
        from_linear(bl),
        alpha8(alpha),
    )
}

/// The lowest and highest linear-light values that still round into 0..=255.
const GAMUT_LO: f64 = -0.000_151_763_491_774_418_76;
const GAMUT_HI: f64 = 1.004_466_356_583_836_8;

/// CSS `oklab(l a b / alpha)` as 8-bit sRGB; `None` outside sRGB or for a non-finite
/// component. `l` is 0..=1.
pub fn oklab_to_rgba8(l: f64, a: f64, b: f64, alpha: f64) -> Option<Rgba8> {
    if !(l.is_finite() && a.is_finite() && b.is_finite() && alpha.is_finite()) {
        return None;
    }
    let lin = oklab_to_linear([math::clamp(l, 0.0, 1.0), a, b]);
    if lin.iter().any(|v| !(GAMUT_LO..=GAMUT_HI).contains(v)) {
        return None;
    }
    Some(Rgba8::new(
        from_linear(lin[0]),
        from_linear(lin[1]),
        from_linear(lin[2]),
        alpha8(alpha),
    ))
}

/// CSS `oklch(l c h / alpha)` with `h` in degrees; `None` outside sRGB.
pub fn oklch_to_rgba8(l: f64, c: f64, h: f64, alpha: f64) -> Option<Rgba8> {
    if !(c.is_finite() && h.is_finite()) {
        return None;
    }
    let (s, co) = math::sin_cos_deg(h);
    let c = if c < 0.0 { 0.0 } else { c };
    oklab_to_rgba8(l, c * co, c * s, alpha)
}

